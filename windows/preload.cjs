const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("likedSongs", {
  loadLibrary: () => ipcRenderer.invoke("library:load"),
  saveLibrary: (state) => ipcRenderer.invoke("library:save", state),
  onPrepareToClose: (callback) => ipcRenderer.on("app:prepare-close", () => callback()),
  readyToClose: () => ipcRenderer.send("app:close-ready"),
  importAudio: () => ipcRenderer.invoke("library:import"),
  localImportCapabilities: () => ipcRenderer.invoke("local-import:capabilities"),
  fetchLocalImportArtwork: (url) => ipcRenderer.invoke("local-import:artwork", { url }),
  previewLocalImport: (sourceURL) => ipcRenderer.invoke("local-import:preview", { sourceURL }),
  cancelLocalImportPreview: () => ipcRenderer.invoke("local-import:preview:cancel"),
  resolveLocalImport: (value) => ipcRenderer.invoke("local-import:resolve", value),
  startLocalImport: (value) => ipcRenderer.invoke("local-import:start", value),
  startExternalImport: (value) => ipcRenderer.invoke("local-import:start-external", value),
  cancelLocalImport: () => ipcRenderer.invoke("local-import:cancel"),
  uploadLocalImport: (value) => ipcRenderer.invoke("local-import:upload", value),
  onLocalImportProgress: (callback) => ipcRenderer.on("local-import:progress", (_event, value) => callback(value)),
  deleteAudio: (filePath) => ipcRenderer.invoke("library:delete", filePath),
  storageSummary: () => ipcRenderer.invoke("library:storage"),
  fetchCatalog: (settings) => ipcRenderer.invoke("server:catalog", settings),
  fetchServerArtwork: (settings) => ipcRenderer.invoke("server:artwork", settings),
  fetchProfiles: (settings) => ipcRenderer.invoke("server:profiles:get", settings),
  createProfile: (settings) => ipcRenderer.invoke("server:profiles:create", settings),
  fetchPlaylists: (settings) => ipcRenderer.invoke("server:playlists:get", settings),
  putPlaylists: (settings) => ipcRenderer.invoke("server:playlists:put", settings),
  postListeningHistory: (settings) => ipcRenderer.invoke("server:listening-history:post", settings),
  fetchListeningHistory: (settings) => ipcRenderer.invoke("server:listening-history:get", settings),
  syncServer: (settings) => ipcRenderer.invoke("server:sync", settings),
  uploadServer: (settings) => ipcRenderer.invoke("server:upload", settings),
  cancelServerTransfer: () => ipcRenderer.invoke("server:cancel-transfer"),
  deleteServerSong: (settings) => ipcRenderer.invoke("server:delete", settings),
  loadServerCredentials: () => ipcRenderer.invoke("server:credentials:load"),
  saveServerCredentials: (credentials) => ipcRenderer.invoke("server:credentials:save", credentials),
  onTransferProgress: (callback) => ipcRenderer.on("server:transfer-progress", (_event, value) => callback(value)),
  openAdmin: (baseURL) => ipcRenderer.invoke("server:open-admin", baseURL),
  checkForUpdates: () => ipcRenderer.invoke("update:check"),
  getUpdateStatus: () => ipcRenderer.invoke("update:state"),
  installUpdate: () => ipcRenderer.invoke("update:install"),
  onUpdateStatus: (callback) => ipcRenderer.on("update:status", (_event, value) => callback(value)),
});
